// Medidas compartilhadas entre telas para manter o conteudo fora da TabBar flutuante.

/** Altura da pilula da TabBar customizada. */
export const TAB_BAR_HEIGHT = 64;

/** Distancia entre a TabBar e a borda inferior segura da tela. */
export const TAB_BAR_MARGIN = 16;

/** Espaco a reservar no fim de listas/scrolls para nao ficar sob a TabBar. */
export const TAB_BAR_SPACE = TAB_BAR_HEIGHT + TAB_BAR_MARGIN * 2;
